package com.apepdcl.gis_survey.estimates.models;

public class InfoModel {
    private String DESCRIPTION;
    private String FEATURE;
    private String FEATURE_SUB_TYPE;

    public String getDESCRIPTION() {
        return DESCRIPTION;
    }

    public void setDESCRIPTION(String DESCRIPTION) {
        this.DESCRIPTION = DESCRIPTION;
    }

    public String getFEATURE() {
        return FEATURE;
    }

    public void setFEATURE(String FEATURE) {
        this.FEATURE = FEATURE;
    }

    public String getFEATURE_SUB_TYPE() {
        return FEATURE_SUB_TYPE;
    }

    public void setFEATURE_SUB_TYPE(String FEATURE_SUB_TYPE) {
        this.FEATURE_SUB_TYPE = FEATURE_SUB_TYPE;
    }
}
